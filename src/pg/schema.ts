/**
 * Schema do Postgres gerado a partir do schema SQLite (fonte única): o mesmo
 * SCHEMA + migrações rodam num SQLite em memória e o DDL resultante é traduzido.
 * Tipos espelhados: INTEGER→BIGINT, REAL→DOUBLE PRECISION, TEXT→TEXT (datas
 * continuam texto, como no SQLite). Colunas novas viram ALTER TABLE ADD COLUMN.
 */
import type { DatabaseSync } from 'node:sqlite';
import type { AsyncDb, Row } from './api.js';
import { translateFunctions } from './translate.js';

interface TableDef { name: string; sql: string; refs: string[] }

function pgType(sqliteType: string): string {
  const t = sqliteType.toUpperCase();
  if (t.includes('INT')) return 'BIGINT';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return 'DOUBLE PRECISION';
  return 'TEXT';
}

function translateCreateTable(sql: string): string {
  let s = sql.replace(/^CREATE TABLE\s+(IF NOT EXISTS\s+)?/i, 'CREATE TABLE IF NOT EXISTS ');
  s = s.replace(/\bINTEGER PRIMARY KEY\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  s = s.replace(/\bINTEGER\b/gi, 'BIGINT');
  s = s.replace(/\bREAL\b/gi, 'DOUBLE PRECISION');
  return translateFunctions(s);
}

/** Lista ordenada (FKs primeiro) de comandos CREATE para o Postgres. */
export function pgSchemaStatements(mem: DatabaseSync): string[] {
  const tables = (mem.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all() as Row[]).map((r) => {
    const sql = String(r.sql);
    const refs = [...sql.matchAll(/REFERENCES\s+([a-z_]+)/gi)].map((m) => (m[1] ?? '').toLowerCase());
    return { name: String(r.name), sql, refs } satisfies TableDef;
  });
  const ordered: TableDef[] = [];
  const done = new Set<string>();
  while (ordered.length < tables.length) {
    const next = tables.find((t) => !done.has(t.name) && t.refs.every((r) => r === t.name || done.has(r)));
    if (!next) throw new Error('dependência circular entre tabelas');
    ordered.push(next);
    done.add(next.name);
  }
  const indexes = (mem.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL").all() as Row[]).map((r) => String(r.sql).replace(/^CREATE INDEX\s+(IF NOT EXISTS\s+)?/i, 'CREATE INDEX IF NOT EXISTS '));
  return [...ordered.map((t) => translateCreateTable(t.sql)), ...indexes];
}

/** Ordem de cópia/criação respeitando FKs. */
export function tableOrder(mem: DatabaseSync): string[] {
  return pgSchemaStatements(mem).filter((s) => s.startsWith('CREATE TABLE')).map((s) => (/CREATE TABLE IF NOT EXISTS\s+"?([a-z_]+)/i.exec(s)?.[1] ?? '').toLowerCase());
}

/** Cria o que falta no Postgres: tabelas, índices e colunas acrescentadas depois. */
export async function ensurePgSchema(db: AsyncDb, mem: DatabaseSync): Promise<void> {
  for (const stmt of pgSchemaStatements(mem)) await db.exec(stmt);
  const tables = (mem.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").all() as Row[]).map((r) => String(r.name));
  for (const table of tables) {
    const have = new Set((await db.prepare('SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ?').all(table)).map((r) => String(r.column_name)));
    for (const col of mem.prepare(`PRAGMA table_info(${table})`).all() as Row[]) {
      const name = String(col.name);
      if (have.has(name)) continue;
      const dflt = col.dflt_value === null || col.dflt_value === undefined ? '' : ` DEFAULT ${translateFunctions(String(col.dflt_value))}`;
      const notNull = Number(col.notnull) === 1 && dflt ? ' NOT NULL' : '';
      await db.exec(`ALTER TABLE ${table} ADD COLUMN ${name} ${pgType(String(col.type))}${dflt}${notNull}`);
    }
  }
}
