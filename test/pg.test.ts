import { test } from 'node:test';
import assert from 'node:assert/strict';
import { statements, TxState } from '../src/pg/txstate.js';

test('statements: separa por ; fora de aspas', () => {
  assert.deepEqual(statements("BEGIN; INSERT INTO t VALUES ('a;b'); COMMIT;"), ['BEGIN', "INSERT INTO t VALUES ('a;b')", 'COMMIT']);
});

test('TxState: conexão cai em transação → erro até ROLLBACK, nunca continua', () => {
  const t = new TxState();
  assert.deepEqual(t.before('BEGIN'), { run: true });
  t.after('BEGIN');
  assert.equal(t.inTx, true);
  t.connectionLost();
  const v = t.before('INSERT INTO x VALUES (1)');
  assert.equal(v.run, false);
  assert.equal(v.run === false && v.reply, 'error');
  const c = t.before('COMMIT');
  assert.equal(c.run === false && c.reply, 'error');
  assert.equal(t.before('SELECT 1').run, true);
  t.after('BEGIN');
  t.connectionLost();
  const r = t.before('ROLLBACK');
  assert.equal(r.run === false && r.reply, 'ok');
  assert.equal(t.before('SELECT 1').run, true);
});

test('TxState: queda fora de transação não bloqueia nada', () => {
  const t = new TxState();
  t.after('BEGIN; SELECT 1; COMMIT');
  t.connectionLost();
  assert.equal(t.before('SELECT 1').run, true);
});

// Contra o Postgres de ensaio (só quando DATABASE_URL existe): mata a própria conexão no meio da transação.
test('pg: backend encerrado durante a transação vira erro NUTROLAB_TX_LOST', { skip: !process.env.DATABASE_URL }, async () => {
  const { PgDb } = await import('../src/pg/pgdb.js');
  const db = new PgDb(process.env.DATABASE_URL as string);
  await db.connect();
  await db.exec('CREATE TABLE IF NOT EXISTS tx_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v BIGINT)');
  await db.exec('DELETE FROM tx_probe');
  await db.exec('BEGIN');
  await db.prepare('INSERT INTO tx_probe (v) VALUES (?)').run(1);
  await assert.rejects(db.prepare('SELECT pg_terminate_backend(pg_backend_pid())').get());
  await assert.rejects(db.prepare('INSERT INTO tx_probe (v) VALUES (?)').run(2), (e: Error & { code?: string }) => e.code === 'NUTROLAB_TX_LOST');
  await db.exec('ROLLBACK');
  const n = await db.prepare('SELECT COUNT(*) AS n FROM tx_probe').get();
  assert.equal(n?.n, 0);
  await db.exec('DROP TABLE tx_probe');
  await db.close();
});

test('pg: consultas emitidas sem esperar rodam na ordem de emissão, e erro não trava a fila', { skip: !process.env.DATABASE_URL }, async () => {
  const { PgDb } = await import('../src/pg/pgdb.js');
  const db = new PgDb(process.env.DATABASE_URL as string);
  await db.connect();
  await db.exec('CREATE TABLE IF NOT EXISTS async_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v BIGINT)');
  await db.exec('DELETE FROM async_probe');
  const r = await db.prepare('INSERT INTO async_probe (v) VALUES (?)').run(7);
  assert.ok(r.lastInsertRowid > 0);
  assert.equal(r.changes, 1);
  // 30 rodadas: escrita e leitura emitidas juntas, sem await entre elas; a leitura enxerga a escrita.
  for (let i = 0; i < 30; i += 1) {
    const write = db.prepare('INSERT INTO async_probe (v) VALUES (?)').run(8);
    const failing = db.prepare('SELECT * FROM tabela_que_nao_existe').get();
    const read = db.prepare('SELECT COUNT(*) AS n FROM async_probe').get();
    await write;
    await assert.rejects(failing, /tabela_que_nao_existe/);
    assert.equal((await read)?.n, 2 + i, `rodada ${i}`);
  }
  // BEGIN emitido sem await vale para as consultas seguintes (mesma conexão, mesma ordem).
  const begin = db.exec('BEGIN');
  const ins = db.prepare('INSERT INTO async_probe (v) VALUES (?)').run(9);
  const rollback = db.exec('ROLLBACK');
  await Promise.all([begin, ins, rollback]);
  const nine = await db.prepare('SELECT COUNT(*) AS n FROM async_probe WHERE v = 9').get();
  assert.equal(nine?.n, 0);
  const rows = await db.prepare('SELECT v FROM async_probe ORDER BY id LIMIT 2').all();
  assert.deepEqual(rows.map((x) => x.v), [7, 8]);
  await db.exec('DROP TABLE async_probe');
  await db.close();
});

// Regressão de 2026-11-24: o sqlite_master descarta o IF NOT EXISTS, e o gerador só repunha em
// CREATE INDEX; o CREATE UNIQUE INDEX do SSO derrubava o segundo boot do processo (42P07).
test('pgSchemaStatements: todo índice (inclusive UNIQUE) nasce com IF NOT EXISTS', async () => {
  const { pgSchemaStatements } = await import('../src/pg/schema.js');
  const { schemaReference } = await import('../src/db.js');
  const indexes = pgSchemaStatements(schemaReference()).filter((s) => /INDEX/i.test(s));
  assert.ok(indexes.length > 0);
  for (const s of indexes) assert.match(s, /^CREATE (UNIQUE )?INDEX IF NOT EXISTS /, s);
  assert.ok(indexes.some((s) => s.startsWith('CREATE UNIQUE INDEX IF NOT EXISTS idx_users_gotrue_sub')), 'índice único do SSO preservado como UNIQUE');
});
