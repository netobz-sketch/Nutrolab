import { test } from 'node:test';
import assert from 'node:assert/strict';
import { statements, TxState } from '../src/pg/txstate.js';

test('statements: separa por ; fora de aspas', () => {
  assert.deepEqual(statements("BEGIN; INSERT INTO t VALUES ('a;b'); COMMIT;"), ['BEGIN', "INSERT INTO t VALUES ('a;b')", 'COMMIT']);
});

test('TxState: conexão cai em transação → erro até ROLLBACK, nunca continua', () => {
  const t = new TxState();
  assert.deepEqual(t.before('BEGIN'), { run: true });
  t.after('BEGIN');
  assert.equal(t.inTx, true);
  t.connectionLost();
  const v = t.before('INSERT INTO x VALUES (1)');
  assert.equal(v.run, false);
  assert.equal(v.run === false && v.reply, 'error');
  const c = t.before('COMMIT');
  assert.equal(c.run === false && c.reply, 'error');
  assert.equal(t.before('SELECT 1').run, true);
  t.after('BEGIN');
  t.connectionLost();
  const r = t.before('ROLLBACK');
  assert.equal(r.run === false && r.reply, 'ok');
  assert.equal(t.before('SELECT 1').run, true);
});

test('TxState: queda fora de transação não bloqueia nada', () => {
  const t = new TxState();
  t.after('BEGIN; SELECT 1; COMMIT');
  t.connectionLost();
  assert.equal(t.before('SELECT 1').run, true);
});

// Contra o Postgres de ensaio (só quando DATABASE_URL existe): mata a própria conexão no meio da transação.
test('ponte: backend encerrado durante a transação vira erro NUTROLAB_TX_LOST', { skip: !process.env.DATABASE_URL }, async () => {
  const { PgSyncDb } = await import('../src/pg/sync.js');
  const db = new PgSyncDb(process.env.DATABASE_URL as string);
  db.exec('CREATE TABLE IF NOT EXISTS tx_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v BIGINT)');
  db.exec('DELETE FROM tx_probe');
  db.exec('BEGIN');
  db.prepare('INSERT INTO tx_probe (v) VALUES (?)').run(1);
  assert.throws(() => db.prepare('SELECT pg_terminate_backend(pg_backend_pid())').get());
  assert.throws(() => db.prepare('INSERT INTO tx_probe (v) VALUES (?)').run(2), (e: Error & { code?: string }) => e.code === 'NUTROLAB_TX_LOST');
  db.exec('ROLLBACK');
  const n = db.prepare('SELECT COUNT(*) AS n FROM tx_probe').get();
  assert.equal(n?.n, 0);
  db.exec('DROP TABLE tx_probe');
  db.close();
});

test('ponte: API assíncrona e síncrona na mesma conexão, em ordem', { skip: !process.env.DATABASE_URL }, async () => {
  const { PgSyncDb } = await import('../src/pg/sync.js');
  const db = new PgSyncDb(process.env.DATABASE_URL as string);
  const adb = db.async;
  await adb.exec('CREATE TABLE IF NOT EXISTS async_probe (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v BIGINT)');
  await adb.exec('DELETE FROM async_probe');
  const r = await adb.prepare('INSERT INTO async_probe (v) VALUES (?)').run(7);
  assert.ok(r.lastInsertRowid > 0);
  assert.equal(r.changes, 1);
  // escrita assíncrona seguida de leitura síncrona: a fila do worker preserva a ordem
  const pending = adb.prepare('INSERT INTO async_probe (v) VALUES (?)').run(8);
  const sync = db.prepare('SELECT COUNT(*) AS n FROM async_probe').get();
  await pending;
  assert.equal(sync?.n, 2);
  const rows = await adb.prepare('SELECT v FROM async_probe ORDER BY id').all();
  assert.deepEqual(rows.map((x) => x.v), [7, 8]);
  await assert.rejects(adb.prepare('SELECT * FROM tabela_que_nao_existe').get(), /tabela_que_nao_existe/);
  await adb.exec('DROP TABLE async_probe');
  db.close();
});
